"""Build data/evidence.json from rules.json, the manifest and snapshot text.

Every excerpt must be found verbatim in its snapshot or the build fails.
    python build_evidence.py
"""
from __future__ import annotations

import json
import sys
from collections import defaultdict

from extract import find_span, snapshot_text
from models import load_rules
from sources import ROOT, load_manifest

EVIDENCE_PATH = ROOT / "data" / "evidence.json"

# Hand-picked program description lines (verbatim, checked 2026-11-05).
CONTEXT: dict[str, tuple[str, list[str]]] = {
    "STU-01": ("S1", [
        "To receive student financial aid, you must meet all of these basic eligibility criteria:",
        "You can only apply to one province for funding.",
        "You may not be eligible if you are:",
    ]),
    "NEW-02": ("S2", [
        "The Province of British Columbia supports organizations across the province to deliver services "
        "for people that are on temporary work and study permits, including new citizens.",
        "help with finding a job",
        "English language practice",
    ]),
    "NEW-03": ("S3", [
        "You can get our free settlement services if you're eligible.",
        "Starting April 1, 2026, economic class permanent residents can only access newcomer services "
        "for a limited time.",
        "Do not enter a full address.",
    ]),
}


def build() -> list[dict]:
    manifest = {s.source_id: s for s in load_manifest()}
    texts: dict[str, str] = {}
    counters: dict[str, int] = defaultdict(int)
    records: list[dict] = []
    errors: list[str] = []

    def add(source_id, program_id, excerpt, kind, rule_id):
        src = manifest[source_id]
        if source_id not in texts:
            texts[source_id] = snapshot_text(source_id)
        if not find_span(texts[source_id], excerpt):
            errors.append(f"{source_id} {kind} {rule_id or ''}: not verbatim: {excerpt[:60]}")
            return
        n = counters[source_id]
        counters[source_id] += 1
        records.append({
            "evidence_id": f"{source_id}@{src.sha256[:8]}#{n:02d}",
            "source_id": source_id, "program_id": program_id, "source_version": src.sha256,
            "excerpt": excerpt, "kind": kind, "rule_id": rule_id,
            "title": src.title, "publisher": src.publisher, "canonical_url": src.canonical_url,
            "captured_on": src.captured_at or (src.snapshot_path or "").split("_")[-1][:8] or None,
            "reuse_status": src.reuse_status,
        })

    for r in load_rules():
        add(r.source_id, r.program_id, r.evidence_span, "rule_span", r.rule_id)
        for e in r.exceptions:
            add(r.source_id, r.program_id, e, "exception", r.rule_id)
    for program_id, (source_id, lines) in CONTEXT.items():
        for line in lines:
            add(source_id, program_id, line, "context", None)

    if errors:
        print("Evidence build FAILED:\n  " + "\n  ".join(errors))
        sys.exit(1)
    return sorted(records, key=lambda x: x["evidence_id"])


def main() -> None:
    records = build()
    EVIDENCE_PATH.write_text(json.dumps({
        "note": "Generated by build_evidence.py. Do not edit by hand. Excerpts are short verbatim spans; "
                "see docs/reuse_terms.md before publishing S1/S2 excerpts.",
        "evidence": records}, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    by_kind: dict[str, int] = defaultdict(int)
    for x in records:
        by_kind[x["kind"]] += 1
    print(f"{len(records)} evidence records -> data/evidence.json  {dict(by_kind)}")


if __name__ == "__main__":
    main()
